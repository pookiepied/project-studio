import type { ChatConversation, ChatMessage } from "../../../types";
import { makeClaudeNativeConversationId } from "./claudeConversationPaths";

interface ParsedClaudeLine {
  type?: string;
  isSidechain?: boolean;
  timestamp?: string;
  uuid?: string;
  origin?: {
    kind?: string;
  };
  toolUseResult?: unknown;
  sourceToolAssistantUUID?: string;
  sessionId?: string;
  cwd?: string;
  version?: string;
  gitBranch?: string;
  message?: {
    role?: string;
    content?: unknown;
    model?: string;
  };
}

function toTimestamp(value: string | undefined, fallback: number): number {
  if (!value) return fallback;
  const parsed = Date.parse(value);
  return Number.isFinite(parsed) ? parsed : fallback;
}

function contentPartToText(part: unknown): string | null {
  if (!part || typeof part !== "object") return null;
  const block = part as Record<string, unknown>;
  if (block.type === "text" && typeof block.text === "string") return block.text;
  return null;
}

function hasInternalToolContent(content: unknown): boolean {
  return Array.isArray(content) && content.some((part) => {
    if (!part || typeof part !== "object") return false;
    const type = (part as Record<string, unknown>).type;
    return type === "tool_use" || type === "tool_result";
  });
}

function messageContentToText(content: unknown): string {
  if (typeof content === "string") return content;
  if (!Array.isArray(content)) return "";
  return content
    .map(contentPartToText)
    .filter((value): value is string => Boolean(value && value.trim()))
    .join("\n\n");
}

function isOperationalUserText(text: string): boolean {
  const normalized = text.replace(/\s+/g, " ").trim().toLowerCase();
  if (!normalized) return true;

  return (
    normalized.includes("local command caveat") ||
    normalized.includes("generated by user while running local command") ||
    normalized.includes("do not respond to these messages") ||
    normalized.includes("command stdout") ||
    normalized.includes("command stderr") ||
    normalized.includes("<command-name>/") ||
    normalized.includes("<command-message>") ||
    normalized.includes("<command-args>") ||
    normalized.includes("<local-command") ||
    normalized.startsWith("<system-reminder>") ||
    normalized.startsWith("/model") ||
    normalized.startsWith("<command-name>/model") ||
    normalized.startsWith("<command-name>/compact") ||
    normalized.startsWith("switched model to ") ||
    normalized.startsWith("model set to ") ||
    normalized.includes("base directory for this skill:") ||
    normalized.includes("\\temp\\claude\\bundled-skills\\") ||
    normalized.includes("/temp/claude/bundled-skills/") ||
    normalized.includes("bundled-skills")
  );
}

function isCompactionText(text: string): boolean {
  const normalized = text.replace(/\s+/g, " ").trim().toLowerCase();
  return (
    normalized.startsWith("this session is being continued from a previous conversation") ||
    normalized.startsWith("summary of the conversation so far") ||
    normalized.startsWith("conversation summary:")
  );
}

function titleFromMessages(messages: ChatMessage[], fallback: string): string {
  const firstUser = messages.find((message) => message.role === "user" && message.content.trim());
  if (!firstUser) return fallback;
  const cleaned = firstUser.content.replace(/\s+/g, " ").trim();
  return cleaned.length > 50 ? `${cleaned.slice(0, 47)}...` : cleaned;
}

export function parseClaudeTranscript(
  content: string,
  options: {
    projectKey: string;
    sessionId: string;
    transcriptPath: string;
    updatedAt?: number;
  }
): ChatConversation {
  const messages: ChatMessage[] = [];
  let cwd: string | undefined;
  let model: string | undefined;
  let lastTimestamp = options.updatedAt ?? Date.now();

  for (const rawLine of content.split(/\r?\n/)) {
    if (!rawLine.trim()) continue;

    let line: ParsedClaudeLine;
    try {
      line = JSON.parse(rawLine) as ParsedClaudeLine;
    } catch {
      continue;
    }

    if (line.isSidechain) continue;
    if (line.cwd) cwd = line.cwd;

    const message = line.message;
    if (!message) continue;
    const role = message?.role;
    if (role !== "user" && role !== "assistant") continue;
    if (line.toolUseResult || line.sourceToolAssistantUUID) continue;
    if (role === "user" && hasInternalToolContent(message.content)) continue;
    if (role === "user" && line.origin?.kind && line.origin.kind !== "human") continue;

    const text = messageContentToText(message.content);
    if (!text.trim()) continue;
    if (role === "user" && isOperationalUserText(text)) continue;
    if (role === "user" && isCompactionText(text)) continue;

    const timestamp = toTimestamp(line.timestamp, lastTimestamp);
    lastTimestamp = Math.max(lastTimestamp, timestamp);
    if (role === "assistant" && message.model) model = message.model;

    messages.push({
      id: line.uuid || `claude-${messages.length}-${timestamp}`,
      role,
      content: text,
      timestamp,
    });
  }

  const createdAt = messages[0]?.timestamp ?? lastTimestamp;
  const updatedAt = messages[messages.length - 1]?.timestamp ?? lastTimestamp;
  const id = makeClaudeNativeConversationId(options.projectKey, options.sessionId);

  return {
    id,
    title: titleFromMessages(messages, `Claude session ${options.sessionId.slice(0, 8)}`),
    model: model ?? "claude",
    messages,
    createdAt,
    updatedAt,
    metadata: {
      storageScope: "local",
      provider: "claude",
      owner: "claude",
      claude: {
        sessionId: options.sessionId,
        cwd,
        model,
        projectKey: options.projectKey,
        transcriptPath: options.transcriptPath,
        lastTurnAt: updatedAt,
      },
    },
  };
}
