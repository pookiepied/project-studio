import {
  capabilityKey,
  type CapabilityDescriptor,
  type ExecutionScope,
} from "../contracts/capabilities.js";
import { hasElevatedEffect, isReadOnly } from "../contracts/effects.js";
import { matchesResource, type ResourceKind } from "./matcher.js";
import type { PermissionScope } from "./scopes.js";

const GIT_NETWORK_SUBCOMMANDS = new Set([
  "fetch",
  "pull",
  "push",
  "clone",
  "ls-remote",
  "remote",
  "submodule",
  "request-pull",
  "send-pack",
  "fetch-pack",
]);

/**
 * What the kernel concluded, and why.
 *
 * `ask` is a real outcome, not a failure. Treating "needs approval" as an error
 * pushes callers into catching it and guessing, which is how approval prompts
 * turn into silent allows.
 */
export type PermissionVerdict = "allow" | "deny" | "ask";

/** Where a decision came from. Rendered to the user, so it must be truthful. */
type DecisionSource =
  /** A rule that cannot be overridden by a grant. */
  | "policy"
  /** A previously stored user decision. */
  | "grant"
  /** The fallback applied when nothing else matched. */
  | "default";

export interface PermissionDecision {
  readonly verdict: PermissionVerdict;
  readonly source: DecisionSource;
  /** Short, user-facing explanation. Never contains call arguments. */
  readonly reason: string;
  /** Set when a stored grant decided this. */
  readonly grantId: string | undefined;
}

export interface PermissionRequest {
  readonly capability: CapabilityDescriptor;
  readonly scope: ExecutionScope;
  /**
   * What the call actually touches — a resolved path, or `git:push`.
   *
   * Derived by the integrator from the call's arguments, never taken from the
   * model verbatim. It is `undefined` for a capability whose arguments do not
   * narrow what it reaches.
   */
  readonly resource: string | undefined;
  /**
   * How wide an approval the user may choose, narrowest first.
   *
   * Generated by the kernel, never by the approver. An approver picks an `id`
   * from this list and cannot supply anything else, so no prompt can grant more
   * than it displayed. See ADR 0015.
   */
  readonly scopes: readonly PermissionScope[];
  /** The longest answer this request accepts; omitted means any. */
  readonly maxDuration?: GrantDuration;
}

/** How long an approval lasts. */
export type GrantDuration =
  /** This call only; nothing is stored. */
  | "once"
  /** Until the conversation ends. */
  | "conversation"
  /** Until the user revokes it. */
  | "always";

/**
 * A rule the user cannot grant their way past.
 *
 * These exist because some decisions are not the user's to make in the moment:
 * a model that can talk a user into one click should not thereby reach an
 * unregistered capability.
 */
export interface PolicyRule {
  readonly id: string;
  /** Returns a verdict to short-circuit, or undefined to fall through. */
  readonly evaluate: (request: PermissionRequest) => PermissionVerdict | undefined;
  readonly reason: string;
}

/**
 * Rules evaluated before any stored grant, in order.
 *
 * Deliberately short. A long list of hardcoded rules is a policy nobody can
 * reason about; the extensibility point is grants, not this array.
 */
export const BASE_POLICY: readonly PolicyRule[] = [
  {
    id: "third-party-elevated",
    reason:
      "Running code or reaching the network from a connected server always needs approval.",
    /**
     * The only thing standing between an unattended mode and third-party code.
     *
     * It must stay a **policy** `ask`: ADR 0018 lets a mode resolve a *default*
     * `ask` and never a policy one, so a verdict reached here survives Auto
     * and a verdict reached by `defaultVerdict` does not. Keying this on
     * anything a connected server could satisfy would make Auto plus one
     * installed server into unattended arbitrary action.
     */
    evaluate: ({ capability }) =>
      capability.provenance.author === "third-party" && hasElevatedEffect(capability)
        ? "ask"
        : undefined,
  },
  {
    id: "computer-sensitive-target",
    reason: "Studio asks before computer input reaches a browser, a password manager, a terminal or a password field, opens a file by path, or reads the clipboard.",
    // P1-4: raised by Studio's own computer server mid-call, through the
    // tool context's `authorize`, once it knows what the input would reach.
    // A policy `ask`, so neither Auto nor a mode answers it; a grant the
    // person chose still does, for as long as the request allowed.
    evaluate: ({ capability, resource }) =>
      capability.provenance.origin === "mcp" && capability.provenance.author === "studio" && (resource ?? "").startsWith("computer:")
        ? "ask"
        : undefined,
  },
  {
    id: "git-network",
    reason: "Git reaching the network always needs approval.",
    // K-04: `git` declares `read`/`write`, so a standing allow rule for the
    // project's writes - or Auto - would push without asking. Rather than
    // declare every git call `network` (which would refuse `git log` on
    // LocalSandbox), force the network subcommands to ask via policy. This
    // survives both because policy `ask` is never resolved by a mode. Duplicated from `tools/git/classify.ts` to avoid a layer
    // inversion between permissions and tools.
    evaluate: ({ capability, resource }) => {
      if (capabilityKey(capability.id) !== "native/git") return undefined;
      const subcommand = (resource ?? "").startsWith("git:")
        ? (resource as string).slice(4)
        : "";
      return GIT_NETWORK_SUBCOMMANDS.has(subcommand) ? "ask" : undefined;
    },
  },
];

/**
 * Builds a rule that matches a capability and, optionally, what it touches.
 *
 * This is the shape user-authored and project-authored rules take: "allow
 * `native/edit` under `src/**`", "always ask before `native/git` `git:push`".
 * Writing them by hand as `evaluate` closures would put arbitrary code in the
 * policy path, where it could not be stored, listed, or shown to a user.
 */
export function resourceRule(input: {
  readonly id: string;
  readonly capability: string;
  readonly resource?: string;
  readonly kind?: ResourceKind;
  readonly verdict: PermissionVerdict;
  readonly reason: string;
}): PolicyRule {
  const kind: ResourceKind = input.kind ?? "path";

  return {
    id: input.id,
    reason: input.reason,
    evaluate: (request) => {
      if (capabilityKey(request.capability.id) !== input.capability) return undefined;
      return matchesResource(input.resource, request.resource, kind)
        ? input.verdict
        : undefined;
    },
  };
}

/**
 * The fallback when no rule and no grant matched.
 *
 * Read-only capabilities from our own code are allowed; everything else asks.
 * Defaulting to `allow` for anything that writes, executes, or reaches the
 * network would mean the first time a user hears about a capability is after it
 * has already run.
 */
export function defaultVerdict(capability: CapabilityDescriptor): PermissionDecision {
  if (isReadOnly(capability) && capability.provenance.author === "studio") {
    return {
      verdict: "allow",
      source: "default",
      reason: "Reads no more than it needs and ships with Project Studio.",
      grantId: undefined,
    };
  }

  return {
    verdict: "ask",
    source: "default",
    reason: `${capabilityKey(capability.id)} has not been approved yet.`,
    grantId: undefined,
  };
}
